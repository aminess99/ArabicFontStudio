const KEYS = Object.keys(FAMILY_NAMES).sort((a, b) => b.length - a.length);

const WEIGHTS: Array<[RegExp, string]> = [
  [/ultralight|extralight|hairline/, "خفيف جداً"],
  [/semibold|demibold|smbd/, "شبه عريض"],
  [/extrabold|exbd|ultrabold/, "عريض جداً"],
  [/black|heavy|fat/, "ثقيل"],
  [/bold|bd$/, "عريض"],
  [/medium|md$/, "متوسط"],
  [/light|lt$/, "خفيف"],
  [/thin/, "رفيع"],
];

const normalise = (value: string) => value.toLowerCase().replace(/[^a-z0-9]/g, "");
const ARABIC = /[؀-ۿ]/;

// The Arabic name for a font, with its weight, or undefined when the family
// is not in the list.
export function arabicFontName(latinName: string): string | undefined {
  const key = normalise(latinName);
  const family = KEYS.find((item) => key.startsWith(item));
  if (!family) return undefined;
  const rest = key.slice(family.length);
  const weight = WEIGHTS.find(([pattern]) => pattern.test(rest))?.[1];
  const italic = /italic|oblique|slant/.test(rest) ? " مائل" : "";
  return `${FAMILY_NAMES[family]}${weight ? ` ${weight}` : ""}${italic}`;
}

// Fills in an Arabic name for fonts stored with only a Latin one.
export function withArabicName<T extends { name: string; nameArabic: string }>(font: T): T {
  if (ARABIC.test(font.nameArabic)) return font;
  const arabic = arabicFontName(font.name);
  return arabic ? { ...font, nameArabic: arabic } : font;
}

// "تجوال عريض Tajawal Bold": both names, as people search either.
export function fontTitleName(font: { name: string; nameArabic: string }): string {
  return font.nameArabic !== font.name && ARABIC.test(font.nameArabic) ? `${font.nameArabic} ${font.name}` : font.nameArabic;
}

// Latin family keys whose Arabic name contains the query, for search.
export function familyKeysForArabicQuery(query: string): string[] {
  const q = query.trim();
  if (!q || !ARABIC.test(q)) return [];
  return KEYS.filter((key) => FAMILY_NAMES[key].includes(q));
}
